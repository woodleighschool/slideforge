// Packages the generated .pptx together with any resources that couldn't be
// embedded inside it (see oleEmbed.ts's module comment for why pptx/pptm and
// PDFs are in that category) into a single .zip, so a teacher gets one thing
// to save and the attached files travel with the presentation instead of
// depending on a system — Seqta or anything else — to still be there later.
//
// The README is the one part of this that outlives the moment of download:
// the in-app download prompt and the slide's own card text both explain the
// bundle too, but only the README is still sitting there, unzipped, if this
// folder gets reopened or handed to someone else months later.

import JSZip from "jszip";

import { dataUrlToBase64 } from "./oleEmbed.js";

export interface BundledResource {
  filename: string;
  dataUrl: string;
}

export interface ResourceBundle {
  bytes: ArrayBuffer;
  fileName: string;
}

/** Appends " (2)", " (3)", … before the extension until the name is unused —
 * two resources with the same filename shouldn't silently overwrite one
 * another in the Resources folder. */
function uniqueFileName(filename: string, used: ReadonlySet<string>): string {
  if (!used.has(filename)) return filename;
  const dot = filename.lastIndexOf(".");
  const base = dot === -1 ? filename : filename.slice(0, dot);
  const ext = dot === -1 ? "" : filename.slice(dot);
  for (let n = 2; ; n++) {
    const candidate = `${base} (${n})${ext}`;
    if (!used.has(candidate)) return candidate;
  }
}

function buildReadme(outputName: string, resourceNames: readonly string[]): string {
  const list = resourceNames.map((name) => `- ${name}`).join("\n");
  return (
    `This folder contains ${outputName}.pptx and the resource files its slides refer to.\n\n` +
    `Keep them together — the presentation's resource cards point to these files in the ` +
    `Resources folder below:\n\n${list}\n\n` +
    `Generated by SlideFORGE.\n`
  );
}

/** Writes each resource under its original filename into `Resources/`
 * inside `zip`, disambiguating any that share a name, and returns the
 * names actually used (for the README). Shared by both bundle builders
 * below. */
function addResourcesToZip(zip: JSZip, resources: readonly BundledResource[]): string[] {
  const used = new Set<string>();
  const names: string[] = [];
  for (const resource of resources) {
    const name = uniqueFileName(resource.filename, used);
    used.add(name);
    names.push(name);
    zip.file(`Resources/${name}`, dataUrlToBase64(resource.dataUrl), { base64: true });
  }
  return names;
}

/** Builds the .zip: `<outputName>.pptx` at the top level, each resource
 * under its original filename in `Resources/`, and a README explaining the
 * bundle. `pptxBytes` should already have any true OLE embeds patched in. */
export async function buildResourceBundle(
  pptxBytes: ArrayBuffer,
  outputName: string,
  resources: readonly BundledResource[],
): Promise<ResourceBundle> {
  const zip = new JSZip();
  zip.file(`${outputName}.pptx`, pptxBytes);

  const names = addResourcesToZip(zip, resources);
  zip.file("README.txt", buildReadme(outputName, names));

  const bytes = await zip.generateAsync({ type: "arraybuffer" });
  return { bytes, fileName: `${outputName}.zip` };
}
